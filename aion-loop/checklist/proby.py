"""ПРОБЫ ВОРОТ — доказывают десять свойств, а не описывают их.

Каждая проба идёт на СВЕЖЕЙ копии во временной папке: настоящее состояние
кандидата опытами не портится.

    python3 proby.py
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

СВОЁ = Path(__file__).parent
ИСХОД = 0


def стенд():
    д = Path(tempfile.mkdtemp(prefix="vorota-proba-"))
    for ф in ("vorota.py", "opredelenie.json", "sostoyanie.json"):
        shutil.copy(СВОЁ / ф, д / ф)
    return д


def зов(д, *дов):
    р = subprocess.run([sys.executable, "vorota.py", *дов], cwd=д,
                       capture_output=True, text=True)
    return р.returncode, ((р.stdout or "") + (р.stderr or "")).strip()


def сост(д):
    return json.loads((д / "sostoyanie.json").read_text(encoding="utf-8"))


def проба(имя, условие, подробно=""):
    global ИСХОД
    сошлось = bool(условие)
    print(f"  [{'ДА ' if сошлось else 'НЕТ'}] {имя}" +
          ("" if сошлось else f"   {подробно}"))
    if not сошлось:
        ИСХОД = 1
    return сошлось


print("ПРОБЫ ВОРОТ КАНДИДАТА")
print()

# 1 — все 69 номеров сохранены
print("1. все 69 номеров на месте")
о = json.loads((СВОЁ / "opredelenie.json").read_text(encoding="utf-8"))
проба("пунктов столько, сколько в порядке", о["пунктов"] == len(о["порядок"]), str(о["пунктов"]))
проба("номера не повторяются", len(set(о["порядок"])) == len(о["порядок"]))
проба("первый N-L0-00", о["порядок"][0] == "N-L0-00", о["порядок"][0])
проба("последний N-COMPLETE-01", о["порядок"][-1] == "N-COMPLETE-01",
      о["порядок"][-1])
проба("все зависимости ссылаются на существующие пункты",
      all(d in о["пункты"] for п in о["пункты"].values() for d in п["depends"]))

# 2 — ровно один готов вначале
print()
print("2. вначале готов ровно один")
д = стенд()
с = сост(д)
готовы = [и for и, п in с["пункты"].items() if п["state"] == "READY"]
проба("READY ровно один", len(готовы) == 1, str(готовы))
проба("и это N-L0-00", готовы == ["N-L0-00"], str(готовы))
проба("DONE ноль", sum(1 for п in с["пункты"].values() if п["state"] == "DONE") == 0)
проба("ACTIVE нет", с["active"] is None, str(с["active"]))

# 3 — перескок закрыт
print()
print("3. перескочить нельзя")
к, в = зов(д, "dispatch", "N-L0-05", "--by", "director")
проба("пункт с незакрытыми зависимостями отвергнут", к == 3 and "не DONE" in в, в[:90])
к, в = зов(д, "dispatch", "N-COMPLETE-01", "--by", "director")
проба("последний пункт тоже не выдаётся", к == 3, в[:90])

# 4 — второго в работе не бывает
print()
print("4. второго в работе не бывает")
зов(д, "dispatch", "N-L0-00", "--by", "director")
к, в = зов(д, "dispatch", "N-L0-01", "--by", "director")
проба("второй отвергнут", к == 3 and "MAX_ACTIVE" in в, в[:90])

# 5 — работник не ставит себе зачёт
print()
print("5. работник не ставит себе зачёт")
к, в = зов(д, "report", "DONE", "--by", "worker", "--evidence", "у")
проба("исход DONE от работника отвергнут", к == 3 and "только" in в, в[:90])
к, в = зов(д, "dispatch", "N-L0-01", "--by", "worker")
проба("работник не выбирает себе пункт", к == 3 and "Директор" in в, в[:90])

# 6 — зачёт только от Директора и только с уликами
print()
print("6. зачёт только от Директора и только с уликами")
к, в = зов(д, "report", "PASS_CANDIDATE", "--by", "worker", "--evidence", "прогон-1")
проба("работник вернул PASS_CANDIDATE", к == 0, в[:80])
к, в = зов(д, "validate", "N-L0-00", "--by", "director")
проба("без улик — отказ", к == 3 and "без доказательств" in в, в[:90])
к, в = зов(д, "validate", "N-L0-00", "--by", "worker", "--evidence", "у")
проба("не от Директора — отказ", к == 3 and "только Директор" in в, в[:90])

# 7 — находка вне пункта ничего не двигает
print()
print("7. находка вне пункта ничего не двигает")
до = сост(д)
к, в = зов(д, "finding", "нашёл беду в другом месте", "--by", "worker")
после = сост(д)
проба("находка записана", к == 0 and len(после["находки"]) == 1, в[:80])
проба("в работе тот же пункт", после["active"] == до["active"], str(после["active"]))
проба("состояния пунктов не изменились",
      {и: п["state"] for и, п in после["пункты"].items()} ==
      {и: п["state"] for и, п in до["пункты"].items()})

# 8 — зачёт Директором и ровно один следующий
print()
print("8. зачёт Директором даёт ровно один следующий")
к, в = зов(д, "validate", "N-L0-00", "--by", "director", "--evidence", "прогон-1")
проба("Директор зачёл", к == 0 and "DONE" in в, в[:80])
проба("назван ровно один следующий", "следующий готовый: N-L0-01" in в, в[:90])
с = сост(д)
проба("DONE записан контроллером с именем Директора",
      с["пункты"]["N-L0-00"]["done_by"] == "director",
      str(с["пункты"]["N-L0-00"]["done_by"]))
проба("в работе снова никого", с["active"] is None, str(с["active"]))
к1, в1 = зов(д, "next-ready")
к2, в2 = зов(д, "next-ready")
проба("next-ready предсказуем: два раза одно и то же", в1 == в2 == "N-L0-01",
      f"{в1} / {в2}")

# 9 — FAIL и BLOCKED не создают зачёта
print()
print("9. FAIL и BLOCKED не создают зачёта")
д2 = стенд()
зов(д2, "dispatch", "N-L0-00", "--by", "director")
зов(д2, "report", "FAIL", "--by", "worker", "--evidence", "почему")
с2 = сост(д2)
проба("после FAIL не DONE", с2["пункты"]["N-L0-00"]["state"] == "FAIL",
      с2["пункты"]["N-L0-00"]["state"])
проба("после FAIL в работе никого", с2["active"] is None)
к, в = зов(д2, "next-ready")
проба("тот же пункт снова выдаётся", в == "N-L0-00", в[:60])
д3 = стенд()
зов(д3, "dispatch", "N-L0-00", "--by", "director")
зов(д3, "report", "BLOCKED", "--by", "worker", "--evidence", "что нужно")
проба("после BLOCKED не DONE",
      сост(д3)["пункты"]["N-L0-00"]["state"] == "BLOCKED")

# 10 — завершение проекта только через последний пункт
print()
print("10. PROJECT_COMPLETE только через N-COMPLETE-01")
к, в = зов(д, "complete")
проба("проект не завершён", к == 1 and "НЕЛЬЗЯ" in в, в[:90])
проба("зависимости последнего пункта не пусты",
      len(о["пункты"]["N-COMPLETE-01"]["depends"]) > 0,
      str(о["пункты"]["N-COMPLETE-01"]["depends"]))

# 11 — определение отвечает источнику
print()
print("11. определение сверено с источником")
р = subprocess.run([sys.executable, "sobrat.py", "--сверка"], cwd=СВОЁ,
                   capture_output=True, text=True)
проба("сверка сошлась", р.returncode == 0,
      ((р.stdout or "") + (р.stderr or "")).strip()[:150])

print()
print("ИТОГ:", "ВСЕ ПРОБЫ СОШЛИСЬ" if ИСХОД == 0 else "ЕСТЬ НЕСОШЕДШИЕСЯ")
sys.exit(ИСХОД)
